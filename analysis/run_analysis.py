"""Run every query in kpi_questions.sql and save the results as Markdown tables.

Usage:  python analysis/run_analysis.py
Output: analysis/results.md (renders as tables on GitHub)
"""
import sys
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "pipeline"))
from config import WAREHOUSE_PATH  # noqa: E402

SQL_FILE = Path(__file__).parent / "kpi_questions.sql"
OUTPUT_FILE = Path(__file__).parent / "results.md"


def fmt(value) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:,.2f}".rstrip("0").rstrip(".") if value % 1 else f"{value:,.0f}"
    if isinstance(value, int):
        return f"{value:,}"
    return str(value)


def to_markdown(columns, rows) -> str:
    lines = ["| " + " | ".join(columns) + " |", "|" + "---|" * len(columns)]
    lines += ["| " + " | ".join(fmt(v) for v in row) + " |" for row in rows]
    return "\n".join(lines)


def main() -> None:
    con = duckdb.connect(str(WAREHOUSE_PATH), read_only=True)
    sections = ["# KPI analysis results\n", "Generated by `analysis/run_analysis.py` from the star schema.\n"]
    for block in SQL_FILE.read_text(encoding="utf-8").split(";"):
        lines = block.strip().splitlines()
        if not any(l.strip() and not l.strip().startswith("--") for l in lines):
            continue
        title = next((l.strip("- ").strip() for l in lines if l.strip().startswith("-- Q")), "Query")
        result = con.execute(block)
        columns = [d[0] for d in result.description]
        sections.append(f"## {title}\n\n{to_markdown(columns, result.fetchall())}\n")
    con.close()
    report = "\n".join(sections)
    OUTPUT_FILE.write_text(report, encoding="utf-8")
    print(report.encode("ascii", "replace").decode("ascii"))
    print(f"\nSaved to {OUTPUT_FILE}")


if __name__ == "__main__":
    main()
